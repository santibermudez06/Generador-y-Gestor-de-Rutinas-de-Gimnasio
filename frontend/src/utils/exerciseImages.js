export function getExerciseImage(exercise) {
  if (!exercise) return STITCH_EXERCISE_IMAGES.avatar;
  const name = (exercise.name || '').toLowerCase();
  const muscle = (exercise.muscleGroup?.name || exercise.muscleGroupName || exercise.category || '').toLowerCase();

  // Mapeo específico por nombre de ejercicio
  if (name.includes('banca plano') || (name.includes('banca') && !name.includes('inclinado'))) {
    return STITCH_EXERCISE_IMAGES.benchPress;
  }
  if (name.includes('inclinado') || name.includes('aperturas') || name.includes('fondos') || name.includes('cruces')) {
    return STITCH_EXERCISE_IMAGES.inclineDumbbell;
  }
  if (name.includes('sentadilla') || name.includes('búlgara') || name.includes('zancada')) {
    return STITCH_EXERCISE_IMAGES.squat;
  }
  if (name.includes('prensa') || name.includes('extens') || name.includes('hack') || name.includes('gemelos')) {
    return STITCH_EXERCISE_IMAGES.legPress;
  }
  if (name.includes('dominada') || name.includes('jalón') || name.includes('chin-up')) {
    return STITCH_EXERCISE_IMAGES.pullUp;
  }
  if (name.includes('remo') || name.includes('gironda') || name.includes('pull')) {
    return STITCH_EXERCISE_IMAGES.barbellRow;
  }
  if (name.includes('militar') || name.includes('overhead') || name.includes('arnold') || (name.includes('press') && name.includes('hombro'))) {
    return STITCH_EXERCISE_IMAGES.overheadPress;
  }
  if (name.includes('lateral') || name.includes('pájaro') || name.includes('curl') || name.includes('tríceps') || name.includes('polea') || name.includes('martillo') || name.includes('francés')) {
    return STITCH_EXERCISE_IMAGES.lateralRaise;
  }
  if (name.includes('peso muerto') || name.includes('hip thrust') || name.includes('femoral') || name.includes('glúteo')) {
    return STITCH_EXERCISE_IMAGES.deadlift;
  }

  // Mapeo por grupo muscular si no coincide el nombre exacto
  if (muscle.includes('pecho')) return STITCH_EXERCISE_IMAGES.benchPress;
  if (muscle.includes('espalda')) return STITCH_EXERCISE_IMAGES.barbellRow;
  if (muscle.includes('hombro')) return STITCH_EXERCISE_IMAGES.overheadPress;
  if (muscle.includes('bíceps') || muscle.includes('tríceps')) return STITCH_EXERCISE_IMAGES.lateralRaise;
  if (muscle.includes('cuádricep') || muscle.includes('pierna')) return STITCH_EXERCISE_IMAGES.squat;
  if (muscle.includes('isquio') || muscle.includes('glúteo')) return STITCH_EXERCISE_IMAGES.deadlift;

  return STITCH_EXERCISE_IMAGES.avatar;
}

